// Helper: get XP needed for pet level (exponential curve)
export function getPetXPForLevel(level: number): number {
  return Math.floor(100 * Math.pow(1.18, level - 1))
}

// Helper: calculate scaled stats for a pet at given level
export function calcPetStats(def: PetDefinition, level: number): import('./types').PetStats {
  const g = def.growthCurves
  const b = def.baseStats
  const lvl = level - 1
  return {
    hp: Math.floor(b.hp + g.hp * lvl),
    maxHp: Math.floor(b.hp + g.hp * lvl),
    atk: Math.floor(b.atk + g.atk * lvl),
    def: Math.floor(b.def + g.def * lvl),
    matk: Math.floor(b.matk + g.matk * lvl),
    mdef: Math.floor(b.mdef + g.mdef * lvl),
    spd: Math.floor(b.spd + g.spd * lvl),
    affinity: b.affinity,
  }
}
